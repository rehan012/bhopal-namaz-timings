export function getTimingsFor(date) {
  const month = date.getMonth() + 1
  const day = date.getDate()
  const m = MONTHS[month]
  if (!m || !m.days[day]) return null
  return m.days[day]
}

export function isInRange(date) {
  const month = date.getMonth() + 1
  const year = date.getFullYear()
  return year === 2026 && month >= 9 && month <= 12
}

// Parse "H.MM" + period into a Date object on the given base date.
export function toDateTime(baseDate, raw, period) {
  const [hStr, mStr] = raw.split('.')
  let h = parseInt(hStr, 10)
  const min = parseInt(mStr, 10)
  if (period === 'PM' && h !== 12) h += 12
  if (period === 'AM' && h === 12) h = 0
  const d = new Date(baseDate)
  d.setHours(h, min, 0, 0)
  return d
}

export function formatTime(raw, period) {
  const [hStr, mStr] = raw.split('.')
  let h = parseInt(hStr, 10)
  return `${h}:${mStr} ${period}`
}